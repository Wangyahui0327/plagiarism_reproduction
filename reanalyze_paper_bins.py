"""Reanalyze previously scored GPT-2 sentences using paper-style probability-bin boundary.
No model inference required. Uses input CSV generated by reproduce.py.
"""
import argparse
import csv
import math
from collections import Counter
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

TARGETS = [5, 10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 85, 90, 95]
PAPER_LOGN = [21.64,24.70,27.76,29.79,32.84,34.87,38.92,42.59,48.01,54.07,61.12,66.80,74.21,86.28]
PAPER_BINS = [20,23,26,28,31,33,37,41,46,52,59,65,72,84]

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--scores', required=True, help='Existing sentence_probabilities.csv')
    p.add_argument('--out', default='results_reanalyzed')
    args=p.parse_args()
    out=Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    values=[]
    with open(args.scores, encoding='utf-8-sig', newline='') as f:
        for r in csv.DictReader(f):
            v=float(r['log10_probability'])
            if math.isfinite(v): values.append(v)
    if not values: raise ValueError('No valid probability entries found')
    x=np.array(values, dtype=np.float64)
    n=len(x)
    # b is the *upper* integer boundary for negative log10(p): b-1 < -log10(p) <= b.
    # The representative probability at this boundary is p_b = 10**(-b).
    b=np.ceil(-x).astype(int)
    bins, counts=np.unique(b, return_counts=True)
    covered=100*np.cumsum(counts)/n
    with open(out/'comparison_table3_paperstyle.csv','w',encoding='utf-8',newline='') as f:
        w=csv.writer(f)
        w.writerow(['k_percent','paper_bin','our_bin','bin_delta','paper_log10_N','our_log10_N','log10_difference','bin_count','total_scored'])
        for k, bp, expected in zip(TARGETS, PAPER_BINS, PAPER_LOGN):
            j=int(np.searchsorted(covered,k,side='left'))
            bj=int(bins[j]); nj=int(counts[j])
            # Eq. (6): npop = (nj / n) / p_b, p_b = 10**(-bj)
            log10_npop=math.log10(nj/n)+bj
            # Eq. (8): N ~= (1/p_b) ln(npop)
            log10_N=bj+math.log10(math.log(10)*log10_npop)
            w.writerow([k,bp,bj,bj-bp,expected,round(log10_N,4),round(log10_N-expected,4),nj,n])
            print(f'k={k:>2}% paper_bin={bp:>3} ours_bin={bj:>3}  paper={expected:6.2f} ours={log10_N:7.2f} delta={log10_N-expected:+6.2f}')
    plt.figure(figsize=(8,5))
    plt.step(bins,covered,where='post')
    plt.xlabel('Negative log10 probability upper-bound bin (ceil)')
    plt.ylabel('Share of sample sentences (%)')
    plt.title(f'Figure 6 analogue: {n:,} sentences')
    plt.ylim(0,100)
    plt.tight_layout()
    plt.savefig(out/'figure6_paperstyle.png',dpi=180)
    plt.close()
    print('Scored sentences:',n)
    print('Saved to:',out.resolve())

if __name__=='__main__': main()
